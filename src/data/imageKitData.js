export const HURFA_IMAGEKIT_ASSETS = HURFA_CATALOG_FOLDER_ASSETS;

/**
 * Dynamically queries ImageKit REST API to fetch live files inside /hurfa_catalog/
 */
export async function fetchHurfaCatalogFiles(options = {}) {
  const path = options.path || "/hurfa_catalog/";
  const limit = options.limit || 1000;
  const authHeader = "Basic " + btoa(`${IMAGEKIT_PRIVATE_KEY}:`);

  const urls = [
    `/api/imagekit/v1/files?path=${encodeURIComponent(path)}&limit=${limit}`,
    `https://api.imagekit.io/v1/files?path=${encodeURIComponent(path)}&limit=${limit}`
  ];

  for (const url of urls) {
    try {
      const response = await axios.get(url, {
        headers: { Authorization: authHeader }
      });
      if (Array.isArray(response.data)) {
        return response.data.map((f, i) => {
          let cleanTitle = f.name
            .replace(/_[a-zA-Z0-9]{8,15}\.(png|jpg|jpeg|webp)/i, "")
            .replace(/[_-]/g, " ")
            .trim();
          if (!cleanTitle || cleanTitle.length < 2) cleanTitle = f.name;

          return {
            id: f.fileId || ("hurfa_" + i),
            name: cleanTitle,
            fileName: f.name,
            filePath: f.filePath,
            url: f.url,
            thumbnail: f.thumbnail || f.url,
            size: f.size ? (f.size / 1024 / 1024).toFixed(2) + " MB" : "Unknown",
            width: f.width,
            height: f.height,
            fileType: f.fileType,
            updatedAt: f.updatedAt
          };
        });
      }
    } catch {
      // Try next or fallback
    }
  }

  // Fallback to static catalog list
  return HURFA_CATALOG_FOLDER_ASSETS;
}

/**
 * Builds an optimized ImageKit transformation URL.
 * @param {string} url - Original ImageKit or external image URL.
 * @param {object} transforms - { width, height, quality, format, cropMode, blur }
 * @returns {string} Transformed ImageKit URL
 */
export function buildImageKitUrl(url, transforms = {}) {
  if (!url) return "";
  const { width, height, quality, format, cropMode, blur } = transforms;

  const trParams = [];
  if (width) trParams.push(`w-${width}`);
  if (height) trParams.push(`h-${height}`);
  if (quality) trParams.push(`q-${quality}`);
  if (format && format !== "auto") trParams.push(`f-${format}`);
  if (cropMode) trParams.push(`c-${cropMode}`);
  if (blur) trParams.push(`bl-${blur}`);

  if (trParams.length === 0) return url;

  const trString = `tr:${trParams.join(",")}`;

  if (url.includes("ik.imagekit.io/6dghafkgmq")) {
    if (url.includes("/tr:")) {
      return url.replace(/\/tr:[^/]+/, `/${trString}`);
    }
    return url.replace("ik.imagekit.io/6dghafkgmq/", `ik.imagekit.io/6dghafkgmq/${trString}/`);
  }

  return url;
}

/**
 * Uploads an image file directly to ImageKit REST API in /hurfa_catalog/.
 * @param {File|Blob} file - The file to upload.
 * @param {object} options - { fileName, folder, tags, onProgress }
 * @returns {Promise<object>} Upload response data from ImageKit
 */
export async function uploadToImageKit(file, options = {}) {
  const fileName = options.fileName || file.name || `hurfa_upload_${Date.now()}.jpg`;
  const folder = options.folder || "/hurfa_catalog/";
  const tags = options.tags || ["hurfa", "catalog"];

  const formData = new FormData();
  formData.append("file", file);
  formData.append("fileName", fileName);
  formData.append("folder", folder);
  formData.append("tags", Array.isArray(tags) ? tags.join(",") : tags);
  formData.append("useUniqueFileName", "true");

  const authHeader = "Basic " + btoa(`${IMAGEKIT_PRIVATE_KEY}:`);

  const response = await axios.post(
    "https://upload.imagekit.io/api/v1/files/upload",
    formData,
    {
      headers: {
        Authorization: authHeader
      },
      onUploadProgress: (progressEvent) => {
        if (options.onProgress && progressEvent.total) {
          const percentCompleted = Math.round((progressEvent.loaded * 100) / progressEvent.total);
          options.onProgress(percentCompleted);
        }
      }
    }
  );

  return response.data;
}
